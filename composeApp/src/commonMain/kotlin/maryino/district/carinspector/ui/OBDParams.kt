enum class ParamStatus { OK, WARN, BAD, NA }

fun ParamStatus.color()    = when (this) { ParamStatus.OK -> Clr.Green; ParamStatus.WARN -> Clr.Amber; ParamStatus.BAD -> Clr.Red; ParamStatus.NA -> Clr.T3 }
fun ParamStatus.dimColor() = when (this) { ParamStatus.OK -> Clr.GreenDim; ParamStatus.WARN -> Clr.AmberDim; ParamStatus.BAD -> Clr.RedDim; ParamStatus.NA -> Color(0x0AFFFFFF) }
fun ParamStatus.label()    = when (this) { ParamStatus.OK -> "в норме"; ParamStatus.WARN -> "внимание"; ParamStatus.BAD -> "ошибка"; ParamStatus.NA -> "нет данных" }

enum class ParamCategory(val title: String, val icon: String) {
    ENGINE("Двигатель",      "◎"),
    FUEL("Топливо",          "◈"),
    TEMPERATURE("Температура","◌"),
    ELECTRICAL("Электрика",  "⟡"),
    EXHAUST("Выхлоп / O₂",  "◉"),
    TRANSMISSION("Трансмиссия","⊕"),
    BRAKES("Тормоза",        "◼"),
    SENSORS("Датчики / ОБД", "◫"),
}

data class OBDParam(
    val pid: String,
    val name: String,
    val short: String,
    val category: ParamCategory,
    val value: Float?,
    val unit: String,
    val normMin: Float?,
    val normMax: Float?,
    val desc: String,          // technical 1-liner
    val meaning: String,       // plain-language explanation
    val status: ParamStatus = calcStatus(value, normMin, normMax)
)

private fun calcStatus(v: Float?, lo: Float?, hi: Float?): ParamStatus {
    if (v == null || lo == null || hi == null) return ParamStatus.NA
    val buf = (hi - lo) * 0.12f
    return when {
        v < lo - buf || v > hi + buf -> ParamStatus.BAD
        v < lo || v > hi             -> ParamStatus.WARN
        else                         -> ParamStatus.OK
    }
}

fun Float.fmt(): String {
    val rounded = (this * 10).toInt() / 10f

    return if (this % 1f == 0f) {
        toInt().toString()
    } else {
        rounded.toString()
    }
}

